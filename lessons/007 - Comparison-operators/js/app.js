let num1 = 10;
let num2 = 15;

console.log(num1 == num2); //false

// NOTE: COmparison operators only check values, not data type

console.log(num1 == "10"); //true

// NOTE:if we want to check both the Value and data type we use ===

console.log(num1 === "10"); // false

//---------------------------------------------------------------

console.log(num1 != num2); //true


console.log(num1 != "10"); //false


console.log(num1 !== "10"); // true

//---------------------------------------------------------------

console.log(num1 < num2); //true


console.log(num1 > num2); //false


console.log(num1 <= num2); // true

console.log(num1 >= num2); // false

